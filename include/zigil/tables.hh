	constexpr char ToLower(char c) {
		return (c >= 'A' && c <= 'Z') ? (char)(c - 'A' + 'a') : c;
	}
	/*
	* Both tables are lowercase, so comparing case-insensitively against a mixed
	* case needle leaves the ordering the tables are sorted in untouched and the
	* binary search below stays valid.
	*/
	constexpr bool CaselessLess(std::string_view a, std::string_view b) {
		const size_t shared = a.size() < b.size() ? a.size() : b.size();
		for (size_t i = 0; i < shared; i++) {
			const char ca = ToLower(a[i]);
			const char cb = ToLower(b[i]);
			if (ca != cb) {
				return ca < cb;
			}
		}
		return a.size() < b.size();
	}
	constexpr bool CaselessEqual(std::string_view a, std::string_view b) {
		if (a.size() != b.size()) {
			return false;
		}
		for (size_t i = 0; i < a.size(); i++) {
			if (ToLower(a[i]) != ToLower(b[i])) {
				return false;
			}
		}
		return true;
	}

	constexpr ZydisMnemonic FindMnemonic(std::string_view name) {
		auto it = std::lower_bound(kMnemonics.begin(), kMnemonics.end(), name,
			[](const auto& pair, std::string_view val) {
				return CaselessLess(pair.first, val);
			});
		if (it != kMnemonics.end() && CaselessEqual(it->first, name)) {
			return it->second;
		}
		return ZYDIS_MNEMONIC_INVALID;
	}
	constexpr std::string_view MnemonicToString(ZydisMnemonic mnemonic) {
		// kMnemonics is sorted by name, which for Zydis mnemonics coincides with
		// enum order, so entry i holds the mnemonic with value i + 1 (INVALID == 0).
		size_t index = (size_t)mnemonic - 1;
		if (index >= kMnemonics.size()) {
			return "invalid";
		}
		return kMnemonics[index].first;
	}

	constexpr ZydisRegister FindRegister(std::string_view name) {
		// kRegisters is in enum order, not sorted by name, so a linear scan is used.
		for (const auto& [reg_name, reg] : kRegisters) {
			if (CaselessEqual(reg_name, name)) {
				return reg;
			}
		}
		return ZYDIS_REGISTER_NONE;
	}
	constexpr std::string_view RegisterToString(ZydisRegister reg) {
		// kRegisters is in enum order but no longer contains NONE, so entry i holds
		// the register with value i + 1; NONE (0) underflows and maps to "none".
		size_t index = (size_t)reg - 1;
		if (index >= kRegisters.size()) {
			return "none";
		}
		return kRegisters[index].first;
	}
